export const DICTIONARIES=Object.freeze({
  [LOCALE.EN_US]:EN_US,
  [LOCALE.PT_BR]:PT_BR
});

export function normalizeLocale(value='auto',browserLocale=globalThis.navigator?.language||LOCALE.EN_US){
  const raw=String(value||LOCALE.AUTO);
  if(raw===LOCALE.EN_US||raw.toLowerCase()==='en-us')return LOCALE.EN_US;
  if(raw===LOCALE.PT_BR||raw.toLowerCase()==='pt-br'||raw.toLowerCase().startsWith('pt'))return LOCALE.PT_BR;
  if(raw!==LOCALE.AUTO&&raw.toLowerCase().startsWith('en'))return LOCALE.EN_US;
  const detected=String(browserLocale||'').toLowerCase();
  return detected.startsWith('pt')?LOCALE.PT_BR:LOCALE.EN_US;
}

function interpolate(text,params={}){
  return String(text).replace(/\{([\w.-]+)\}/g,(_,key)=>params[key]??'');
}

export function createLocalization({locale=LOCALE.AUTO,browserLocale=globalThis.navigator?.language||LOCALE.EN_US}={}){
  let requested=String(locale||LOCALE.AUTO);
  let current=normalizeLocale(requested,browserLocale);
  const listeners=new Set();

  function t(key,fallback='',params={}){
    const source=DICTIONARIES[current]||EN_US;
    const value=source[key]??EN_US[key]??fallback??key;
    return interpolate(value,params);
  }
  function apply(root=globalThis.document){
    if(!root?.querySelectorAll)return current;
    root.querySelectorAll('[data-i18n]').forEach(element=>{
      const key=element.dataset.i18n;
      if(key)element.textContent=t(key,element.textContent);
    });
    root.querySelectorAll('[data-i18n-aria-label]').forEach(element=>{
      const key=element.dataset.i18nAriaLabel;
      if(key)element.setAttribute('aria-label',t(key,element.getAttribute('aria-label')||''));
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach(element=>{
      const key=element.dataset.i18nPlaceholder;
      if(key)element.setAttribute('placeholder',t(key,element.getAttribute('placeholder')||''));
    });
    return current;
  }
  function setLocale(next=LOCALE.AUTO){
    requested=String(next||LOCALE.AUTO);
    current=normalizeLocale(requested,browserLocale);
    if(globalThis.document?.documentElement)globalThis.document.documentElement.lang=current;
    apply(globalThis.document);
    for(const listener of listeners)listener(current);
    return current;
  }
  function subscribe(listener){
    if(typeof listener!=='function')return ()=>{};
    listeners.add(listener);
    return ()=>listeners.delete(listener);
  }

  if(globalThis.document?.documentElement)globalThis.document.documentElement.lang=current;
  return {t,apply,setLocale,subscribe,get locale(){return current;},get requestedLocale(){return requested;}};
}

export const defaultLocalization=createLocalization();
